'use strict';
const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const origin='http://127.0.0.1:8080';
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
 try{
  const context=await browser.newContext({viewport:{width:390,height:844},isMobile:true});
  const page=await context.newPage();const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(origin+'/beauty-central/',{waitUntil:'domcontentloaded'});
  await page.waitForFunction(()=>document.querySelectorAll('#productRows tr').length>=8);
  assert.equal(await page.locator('#productRows tr').count(),8);
  assert.equal(await page.locator('#categoryRows .category-tile').count(),6);
  await page.locator('#menuToggle').click();
  await page.locator('#moduleNav [data-module=categories]').click();
  await page.locator('#newCategory').click();
  await page.locator('#categoryForm input[name=name]').fill('Importados');
  await page.locator('#categoryForm input[name=icon]').fill('🪞');
  await page.locator('#categoryForm button[type=submit]').click();
  await page.locator('#categoryDialog').waitFor({state:'hidden'});
  assert.equal(await page.locator('#categoryRows .category-tile').count(),7);
  await page.locator('#menuToggle').click();
  await page.locator('#moduleNav [data-module=products]').click();
  await page.locator('#newProduct').click();
  await page.locator('#productForm input[name=name]').fill('Batom Teste Central');
  await page.locator('#productForm input[name=id]').fill('beauty-sku-0001');
  await page.locator('#productForm select[name=categoryId]').selectOption('importados');
  await page.locator('#productForm input[name=brand]').fill('Marca de Testes');
  await page.locator('#productForm input[name=cost]').fill('12.30');
  await page.locator('#productForm input[name=price]').fill('29.90');
  await page.locator('#productForm input[name=stock]').fill('6');
  await page.locator('#productForm input[name=lot]').fill('L-01');
  await page.locator('#productForm input[name=expiry]').fill('2028-11-01');
  await page.locator('#productForm select[name=regularization]').selectOption('VERIFICADO');
  await page.locator('#productForm input[name=published]').check();
  await page.locator('#productForm button[type=submit]').click();
  await page.locator('#productDialog').waitFor({state:'hidden'});
  assert.match(await page.locator('#productRows').textContent(),/Batom Teste Central/);
  assert.match(await page.locator('#productRows').textContent(),/Pronto para prévia/);
  await page.reload({waitUntil:'domcontentloaded'});
  await page.waitForFunction(()=>document.querySelectorAll('#productRows tr').length===9);
  const record=await page.evaluate(()=>JSON.parse(localStorage.getItem('john_beauty_central_catalog_v1')));
  assert.equal(record.company,'beauty');
  assert.equal(record.products.find(p=>p.id==='beauty-sku-0001')?.price,29.9);
  await page.locator('#menuToggle').click();
  await page.locator('#moduleNav [data-module=settings]').click();
  const transfer=page.waitForEvent('download');
  await page.locator('#exportData').click();
  const download=await transfer;
  assert.match(download.suggestedFilename(),/beauty-central-backup\.json/);
  await page.goto(origin+'/lojas/cosmeticos/?preview=central',{waitUntil:'domcontentloaded'});
  await page.locator('#beautyIdentity').waitFor({state:'visible'});
  await page.locator('#beautyName').fill('Teste Beauty');
  await page.locator('#beautyPhone').fill('11987654321');
  await page.locator('#beautyConsent').check();
  await page.locator('#beautyForm button[type=submit]').click();
  await page.locator('#beautyIdentity').waitFor({state:'hidden'});
  await page.waitForFunction(()=>document.querySelectorAll('#categories .category').length===1);
  assert.match(await page.locator('#categories .category').first().textContent(),/Importados/);
  await page.locator('#tabs [data-page=catalogo]').click();
  assert.equal(await page.locator('#products .product').count(),1);
  assert.match(await page.locator('#products .product').first().textContent(),/Batom Teste Central/);
  await page.goto(origin+'/lojas/cosmeticos/',{waitUntil:'domcontentloaded'});
  await page.waitForFunction(()=>document.querySelector('#empty')?.textContent.includes('preparando nosso catálogo'));
  assert.equal(await page.locator('#products .product').count(),0,'Rascunhos não podem aparecer para clientes normais');
  assert.deepEqual(errors,[],'Sem falhas JS');
  console.log('PASS: Beauty Central CRUD, backup, preview local, isolamento de vitrine pública');
  await context.close();
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1});
